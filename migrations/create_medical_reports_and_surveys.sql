-- Trigger for consultations
create or replace function create_survey_on_consultation_complete()
returns trigger as $$
begin
  if NEW.status = 'completada' and OLD.status != 'completada' then
    insert into consultation_survey_responses
      (consultation_id, patient_id, survey_id, answers)
    select
      NEW.id,
      NEW.patient_id,
      s.id,
      '{}'::jsonb
    from consultation_surveys s
    where s.is_active = true
    order by s.version desc
    limit 1
    on conflict (consultation_id, patient_id) do nothing;
  end if;
  return NEW;
end;
$$ language plpgsql security definer;

-- Drop trigger if exists to allow safe re-run
drop trigger if exists trigger_survey_on_complete on consultation;

create trigger trigger_survey_on_complete
after update on consultation
for each row execute function create_survey_on_consultation_complete();
